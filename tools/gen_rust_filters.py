#!/usr/bin/env python3
"""Build the raw filter text consumed by the optional Rust engine.

This keeps the original upstream filter syntax so adblock-rust can parse rules
that the Kotlin fallback cannot represent. The Android app never downloads or
executes anything from these lists; they are bundled at build-prep time.
"""

from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CACHE = ROOT / "tools" / ".filter-cache"
OUT = ROOT / "app" / "src" / "main" / "assets" / "adblock_filters.txt"

SOURCES = [
    ("easylist.txt", "EasyList - The EasyList authors (https://easylist.to/) - dual CC BY-SA / GPL"),
    ("easyprivacy.txt", "EasyPrivacy - The EasyList authors (https://easylist.to/) - dual CC BY-SA / GPL"),
    ("ubo-filters.txt", "uBlock Origin filters - uBlock Origin contributors (https://github.com/uBlockOrigin/uAssets) - GPL-3.0"),
    ("brave-specific.txt", "Brave-specific - Brave Software (https://github.com/brave/adblock-lists) - MPL-2.0"),
    ("brave-android-specific.txt", "Brave Android-specific - Brave Software - MPL-2.0"),
    ("brave-social.txt", "Brave social - Brave Software - MPL-2.0"),
    ("brave-cookie-specific.txt", "Brave cookie-specific - Brave Software - MPL-2.0"),
    ("brave-firstparty.txt", "Brave first-party - Brave Software - MPL-2.0"),
    ("filters-mirror.txt", "Brave filters mirror - Brave Software - MPL-2.0"),
    ("yt-distracting.txt", "Brave YouTube distracting - Brave Software - MPL-2.0"),
    ("yt-recommended.txt", "Brave YouTube recommended - Brave Software - MPL-2.0"),
    ("yt-shorts.txt", "Brave YouTube Shorts - Brave Software - MPL-2.0"),
]


def usable(line: str) -> bool:
    stripped = line.strip()
    if not stripped or stripped.startswith(("!", "[")):
        return False
    # Comments beginning with a single '#' are dropped, but cosmetic rules
    # ('##', '#@#', '#%#') are kept.
    if stripped.startswith("#") and not stripped.startswith(("##", "#@", "#%", "#$")):
        return False
    # Scriptlet/snippet injections are never executed by this browser.
    if "#?#" in stripped or "#$#" in stripped:
        return False
    return len(stripped) <= 4000


def main() -> None:
    chunks = [
        "! LightweightBrowser bundled filter data for adblock-rust.",
        "! Generated by tools/gen_rust_filters.py. Do not edit by hand.",
        "! No network access and no JavaScript execution from filter lists.",
    ]
    total = 0
    for name, attribution in SOURCES:
        path = CACHE / name
        if not path.is_file():
            print(f"warning: missing cached source {name}; run tools/gen_filters.py first")
            continue
        chunks.append(f"! SOURCE: {attribution}")
        for raw in path.read_text(encoding="utf-8", errors="ignore").splitlines():
            if usable(raw):
                chunks.append(raw.strip())
                total += 1
        chunks.append("! END SOURCE")

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(chunks) + "\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} ({total} rules, {OUT.stat().st_size} bytes)")


if __name__ == "__main__":
    main()
